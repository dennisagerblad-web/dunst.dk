function dunstReviewedPhotoCard(photo) {
  const card = document.createElement("figure");
  card.className = "media-card legacy-box reviewed-profile-photo";
  card.style.setProperty("--legacy-image-width", `${photo.width + 2}px`);

  const image = document.createElement("img");
  image.src = photo.image;
  image.width = photo.width;
  image.height = photo.height;
  image.alt = photo.alt;
  image.loading = "lazy";

  const caption = document.createElement("figcaption");
  caption.className = "performer-photo-caption";
  const link = document.createElement("a");
  link.href = menuDestination(`https://dunst.dk${photo.event}`);
  link.textContent = photo.eventName;
  caption.append(link);
  if (photo.date) caption.append(` · ${photo.date}`);

  card.append(image, caption);
  return card;
}

function appendDunstReviewedPerformerPhotos(root, profilePath) {
  const removed = new Set(dunstRemovedProfilePhotos[profilePath]);
  if (removed.size) {
    for (const image of root.querySelectorAll("img[src]")) {
      if (!removed.has(decodeURIComponent(new URL(image.src).pathname)) || !root.contains(image)) continue;
      const card = image.closest("table.profile-card");
      if (card?.querySelectorAll("img").length === 1) {
        card.remove();
        continue;
      }
      const link = image.closest("a");
      if (link?.querySelectorAll("img").length === 1 && !link.textContent.trim()) link.remove();
      else image.remove();
    }
  }
  for (const photo of dunstReviewedProfilePhotos[profilePath] || []) {
    const sections = [...root.querySelectorAll(":scope > .hairwerk-year")];
    const yearOf = (section) => Number(section.querySelector(":scope > .year-box")?.textContent.replace(/:\s*$/, ""));
    let section = sections.find((item) => yearOf(item) === photo.year);
    if (!section) {
      section = document.createElement("section");
      section.className = "hairwerk-year";
      const title = document.createElement("h2");
      title.className = "year-box";
      title.textContent = `${photo.year}:`;
      const grid = document.createElement("div");
      grid.className = "grid";
      section.append(title, grid);
      root.insertBefore(section, sections.find((item) => yearOf(item) < photo.year) || null);
    }
    section.querySelector(":scope > .grid").append(dunstReviewedPhotoCard(photo));
  }
}

function appendDunstReviewedDjPhotos(profile, profilePath) {
  const photos = dunstReviewedProfilePhotos[profilePath];
  if (!photos?.length) return;
  const gallery = profile.tBodies[0].insertRow().insertCell();
  gallery.colSpan = profile.rows[0].cells[0].colSpan;
  const years = [...new Set(photos.map((photo) => photo.year))].sort((a, b) => b - a);
  for (const year of years) {
    const section = document.createElement("section");
    section.className = "reviewed-dj-photo-year";
    const heading = document.createElement("h3");
    heading.textContent = `${year}:`;
    section.append(heading, ...photos.filter((photo) => photo.year === year).map(dunstReviewedPhotoCard));
    gallery.append(section);
  }
}
